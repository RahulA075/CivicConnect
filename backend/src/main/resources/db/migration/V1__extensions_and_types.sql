-- V1: PostgreSQL extensions and custom ENUM types
-- Mirrors: database/01_extensions_and_types.sql

CREATE EXTENSION IF NOT EXISTS postgis;
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE EXTENSION IF NOT EXISTS pg_trgm;
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TYPE auth_provider AS ENUM ('LOCAL','GOOGLE','PHONE_OTP');
CREATE TYPE user_role AS ENUM ('CITIZEN','FIELD_WORKER','DEPT_SUPERVISOR','MUNICIPAL_ADMIN','SYSTEM_ADMIN');
CREATE TYPE issue_status AS ENUM ('DRAFT','SUBMITTED','ASSIGNED','IN_PROGRESS','RESOLVED','VERIFIED','REOPENED','CLOSED','REJECTED');
CREATE TYPE issue_priority AS ENUM ('LOW','MEDIUM','HIGH','CRITICAL');
CREATE TYPE notification_channel AS ENUM ('PUSH','EMAIL','SMS');
CREATE TYPE notification_event AS ENUM (
    'ISSUE_SUBMITTED','ISSUE_ASSIGNED','ISSUE_IN_PROGRESS','ISSUE_RESOLVED',
    'ISSUE_CLOSED','ISSUE_REOPENED','ISSUE_REJECTED','ISSUE_OVERDUE',
    'ISSUE_ESCALATED','ASSIGNMENT_RECEIVED','SLA_BREACH_WARNING','SLA_BREACHED',
    'RESOLUTION_VERIFY_REQUEST','UPVOTE_RECEIVED','COMMENT_ADDED',
    'ACCOUNT_CREATED','PASSWORD_RESET','OTP_SENT'
);
CREATE TYPE otp_purpose AS ENUM ('REGISTRATION','PASSWORD_RESET','PHONE_CHANGE','LOGIN_MFA');
CREATE TYPE image_type AS ENUM ('EVIDENCE','PROGRESS','RESOLUTION');
CREATE TYPE device_platform AS ENUM ('ANDROID','IOS');
CREATE TYPE audit_entity AS ENUM (
    'USER','ISSUE','DEPARTMENT','CATEGORY','SLA_POLICY',
    'ESCALATION_RULE','MUNICIPALITY','NOTIFICATION_TEMPLATE',
    'WEBHOOK','FEATURE_FLAG','ROLE','SCHEDULED_REPORT'
);
CREATE TYPE audit_action AS ENUM (
    'CREATE','UPDATE','DELETE','LOGIN','LOGOUT','LOGIN_FAILED',
    'PASSWORD_RESET','ROLE_CHANGE','DEACTIVATE','REACTIVATE',
    'ASSIGN','ESCALATE','MERGE','EXPORT'
);
CREATE TYPE report_frequency AS ENUM ('DAILY','WEEKLY','MONTHLY');

-- Utility: auto-update updated_at
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
